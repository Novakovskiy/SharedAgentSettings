#!/usr/bin/env python3
"""Generate agent instruction files from the canonical instructions/ sources."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parent.parent
GENERATED_MARKER = "<!-- Generated by scripts/sync_instructions.py; edit instructions/ instead. -->"


def read_source(name: str) -> str:
    path = ROOT / "instructions" / name
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError as error:
        raise RuntimeError(f"Cannot read instruction source {path}: {error}") from error


def render(provider: str | None = None) -> str:
    sections = [read_source("core.md"), read_source("project.md")]
    if provider:
        sections.append(read_source(f"providers/{provider}.md"))
    return f"{GENERATED_MARKER}\n\n" + "\n\n".join(sections) + "\n"


def write_outputs(outputs: dict[Path, str], force: bool) -> None:
    pending = {}
    for path, content in outputs.items():
        if path.exists():
            existing = path.read_text(encoding="utf-8")
            if existing == content:
                print(f"Up to date: {path}")
                continue
            if not force and GENERATED_MARKER not in existing:
                raise RuntimeError(
                    f"Refusing to overwrite existing unmarked file: {path}. "
                    "Back it up or rerun with --force to replace it."
                )
        pending[path] = content

    for path, content in pending.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Updated: {path}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate AGENTS.md and GitHub Copilot instructions from instructions/."
    )
    parser.add_argument(
        "--target",
        type=Path,
        default=ROOT,
        help="Project directory to install the generated files into (default: this repository).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace existing instruction files, including unmarked project files.",
    )
    args = parser.parse_args()
    target = args.target.expanduser().resolve()

    try:
        write_outputs(
            {
                target / "AGENTS.md": render(),
                target / ".github" / "copilot-instructions.md": render("copilot"),
            },
            args.force,
        )
    except (OSError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

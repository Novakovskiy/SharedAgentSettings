#!/usr/bin/env python3
"""Generate agent instruction files from the canonical instructions/ sources."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parent.parent
GENERATED_MARKER = "<!-- Generated by scripts/sync_instructions.py; edit instructions/ instead. -->"


def render() -> str:
    return (
        f"{GENERATED_MARKER}\n\n"
        "Before acting, read and follow the Markdown instruction files under "
        "`instructions/` in this order: `core.md` first, then all other Markdown "
        "files recursively in ascending relative-path order except "
        "`current-project.md`, and `current-project.md` last. Maintain "
        "`instructions/current-project.md` as the canonical record of durable, "
        "project-specific settings, conventions, and decisions: record them "
        "when established, clarify uncertainty with the user rather than "
        "guessing, and do not put project-specific rules in other instruction "
        "files. Its rules apply to all agents and take priority over any "
        "conflicting instructions in the other files.\n"
    )


def write_outputs(outputs: dict[Path, str], force: bool) -> None:
    pending = {}
    for path, content in outputs.items():
        if path.exists():
            existing = path.read_text(encoding="utf-8")
            if existing == content:
                print(f"Up to date: {path}")
                continue
            if not force and GENERATED_MARKER not in existing:
                raise RuntimeError(
                    f"Refusing to overwrite existing unmarked file: {path}. "
                    "Back it up or rerun with --force to replace it."
                )
        pending[path] = content

    for path, content in pending.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Updated: {path}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate instruction entry points that load the canonical files under instructions/."
    )
    parser.add_argument(
        "--target",
        type=Path,
        default=ROOT,
        help="Project directory to install the generated files into (default: this repository).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace existing instruction files, including unmarked project files.",
    )
    args = parser.parse_args()
    target = args.target.expanduser().resolve()

    try:
        write_outputs(
            {
                target / "AGENTS.md": render(),
                target / ".github" / "copilot-instructions.md": render(),
            },
            args.force,
        )
    except (OSError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
